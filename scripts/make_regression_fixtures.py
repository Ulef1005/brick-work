def build(label, commit, work):
    tree = work / commit
    tree.mkdir()
    archive = subprocess.run(['git', 'archive', commit, 'brickwork'], cwd=ROOT, check=True, capture_output=True).stdout
    subprocess.run(['tar', '-x', '-C', str(tree)], input=archive, check=True)
    target = work / (label + '.db')
    code = ('import sys; from brickwork.core.connect import connect; db=connect(sys.argv[1]); db.close()')
    subprocess.run([sys.executable, '-c', code, str(target)], cwd=tree, check=True, env={'PYTHONPATH': str(tree), 'PATH': '/usr/bin:/bin'})
    with sqlite3.connect(target) as db:
        db.execute('PRAGMA foreign_keys=ON')
        db.executescript(ROWS)
        problems = db.execute('PRAGMA foreign_key_check').fetchall()
        if problems:
            raise SystemExit(f'{label}: foreign key problems {problems}')
        db.execute('PRAGMA journal_mode=DELETE')
    with sqlite3.connect(target) as db:
        db.execute('VACUUM')
    return target


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        for label, commit in POINTS.items():
            made = build(label, commit, Path(tmp))
            shutil.copy(made, OUT / made.name)
            print('built', made.name, made.stat().st_size, 'bytes')


if __name__ == '__main__':
    main()
