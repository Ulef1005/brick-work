"""Brick Work's B′ component stylesheet, generated from the approved frames (#492 part 2).

    python3 scripts/b_prime_css.py check    the drift check (scripts/check.sh); exit 1 on drift
    python3 scripts/b_prime_css.py build    write static/brickwork/b-prime.css from design/sources/b/b_frames.py

design/sources/b/b_frames.py (design's) holds the frames' CSS as plain literals: B_COMPONENTS (the shell and component rules in cascade order),
DARK_CSS and SWAPS (what the dark frames change). This reads them with `ast`, so a rule changes in the frames first. Every rule is scoped under
the root class `.b-prime` (`bp-*` is planning's prefix), so a rebuilt screen or the shell carries B′ without touching an unrebuilt one; the
scope carries three `:not(#_)` so it outranks any class-only legacy rule. Dark is written twice, as the token layer does: in
`@media (prefers-color-scheme: dark)` under `:root:not(.tw-light)`, and under `.tw-dark`. The frames' `html{color-scheme:dark}` is skipped.
Anything the generator cannot scope (an at-rule, a nested block, a selector on html, body or :root) fails the build: say so to design.
Standard library only. Modelled on scripts/tokens_base.py."""
import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'design' / 'sources' / 'b' / 'b_frames.py'
SERVED = ROOT / 'static' / 'brickwork' / 'b-prime.css'
ROOT_CLASS = '.b-prime'
BUMP = ':not(#_):not(#_):not(#_)'
SCOPE = ROOT_CLASS + BUMP
SKIPPED_DARK = {'html'}          # the frames' own page-level dark rule
NAMES = ('B_COMPONENTS', 'DARK_CSS', 'SWAPS')
HEADER = ('/* Brick Work B′ components, served. GENERATED by scripts/b_prime_css.py build from design/sources/b/b_frames.py: never edit this file.\n'
          f'   Every rule is scoped under {ROOT_CLASS}; the dark rules follow the token layer\'s two dark selectors. */\n\n')
BASE = (f'{SCOPE}{{font:400 15px/1.45 var(--tw-font),system-ui,sans-serif;color:var(--tw-text);-webkit-font-smoothing:antialiased}}\n'
        f'{SCOPE} *,{SCOPE} *::before,{SCOPE} *::after{{box-sizing:border-box;margin:0;padding:0}}\n'
        f'{SCOPE} img{{display:block}}\n'
        f'{SCOPE} [hidden]{{display:none!important}}\n'   # the legacy `[hidden]` rule skips .b-prime, and a component's own display would win over the browser's
        f'@media(prefers-reduced-motion:reduce){{{SCOPE},{SCOPE} *,{SCOPE} *::before,{SCOPE} *::after{{animation:none!important;transition:none!important}}}}\n'   # as the legacy reset, which skips .b-prime
        f'{SCOPE} a{{color:inherit;text-decoration:none}}\n'
        f'{SCOPE} button{{font:inherit;color:inherit;background:none;border:0;cursor:pointer}}\n'
        f'{SCOPE} :focus-visible{{outline:var(--tw-focus-width) solid var(--tw-focus-color);outline-offset:var(--tw-focus-offset)}}\n')


def literals(path: Path = SOURCE) -> dict:
    found = {}
    for node in ast.parse(path.read_text(encoding='utf-8')).body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and getattr(node.targets[0], 'id', None) in NAMES:
            found[node.targets[0].id] = ast.literal_eval(node.value)
    missing = [n for n in NAMES if n not in found]
    if missing:
        raise SystemExit(f'B-PRIME: {rel(path)} has no plain literal for {", ".join(missing)}')
    return found


PSUB_MEASURED = 40   # the phone sub row has no height of its own (padding, a 13 px label, a 3 px underline): measured in the pinned Chrome 157 on frame 01, 390 wide


def shell_heights(path: Path = SOURCE) -> dict:
    """The shell's heights in CSS px, read from the frames' own rules (`.top`, `.sub`, `.ptop`, `.tabbar`), for the app-vs-frame band
    (scripts/frame_check.py) and for the offsets the unrebuilt pages use. The phone sub row is the measured constant above."""
    css = literals(path)['B_COMPONENTS']
    css = css if isinstance(css, str) else ''.join(css)
    found = {}
    for key, selector in (('top', '.top'), ('sub', '.sub'), ('ptop', '.ptop'), ('tabbar', '.tabbar')):
        m = re.search(r'(?<![\w.-])' + re.escape(selector) + r'\{(?:[^}]*;)?height:(\d+)px', css)
        if not m:
            raise SystemExit(f'B-PRIME: no height on {selector} in {rel(path)}')
        found[key] = int(m.group(1))
    found['psub'] = PSUB_MEASURED
    return found


def rel(path: Path) -> str:
    try:
        return str(path.relative_to(ROOT))
    except ValueError:
        return str(path)


def split_top(selector: str) -> list[str]:
    parts, depth, cur = [], 0, ''
    for ch in selector:
        depth += ch in '([' 
        depth -= ch in ')]'
        if ch == ',' and depth == 0:
            parts.append(cur.strip())
            cur = ''
        else:
            cur += ch
    parts.append(cur.strip())
    return parts


def rules(css: str) -> list[tuple[str, str]]:
    """`[(selector, declarations)]` of flat rules; an at-rule or a nested block raises."""
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    out, pos = [], 0
    while True:
        start = css.find('{', pos)
        if start < 0:
            break
        end = css.find('}', start)
        if end < 0:
            raise SystemExit(f'B-PRIME: an unclosed rule after {css[pos:start].strip()[:60]!r}')
        selector, body = css[pos:start].strip(), css[start + 1:end]
        if '{' in body or selector.startswith('@') or not selector:
            raise SystemExit(f'B-PRIME: cannot scope {selector or body[:40]!r}: an at-rule or a nested block; ask design for flat rules')
        out.append((selector, body.strip()))
        pos = end + 1
    if css[pos:].strip():
        raise SystemExit(f'B-PRIME: stray text after the last rule: {css[pos:].strip()[:60]!r}')
    return out


# The frames draw the phone sub row's entries as <span> and the tab bar's as <div>; the app uses links there. Each such rule also applies to the link.
ALIASES = (('.psub span', '.psub a'), ('.tabbar div', '.tabbar a'))


def scope(selector: str, prefix: str = SCOPE) -> str:
    parts = split_top(selector)
    parts += [part.replace(old, new) for part in parts for old, new in ALIASES if old in part]
    for part in parts:
        if re.match(r'(html|body|:root)\b', part):
            raise SystemExit(f'B-PRIME: cannot scope {part!r}: a page-level selector')
    return ','.join(f'{prefix} {part}' for part in parts)


def darkened(css: str, swaps: list) -> str:
    for old, new in swaps:
        css = css.replace(old, new)
    return css


def generate(lits: dict | None = None) -> str:
    lits = lits or literals()
    light_css = '\n'.join(lits['B_COMPONENTS'])
    light = rules(light_css)
    dark_css = darkened(light_css, lits['SWAPS'])
    changed = [r for r in rules(dark_css) if r not in light]
    extra = [r for r in rules(lits['DARK_CSS']) if r[0] not in SKIPPED_DARK]
    dark = changed + extra
    out = [HEADER, BASE, '\n/* components */\n'] + [f'{scope(s)}{{{d}}}\n' for s, d in light]
    if dark:
        media = ''.join(f'  {scope(s, ":root:not(.tw-light) " + SCOPE)}{{{d}}}\n' for s, d in dark)
        out.append('\n/* dark: the system setting, unless the page says light */\n@media (prefers-color-scheme: dark) {\n' + media + '}\n')
        out.append('\n/* dark: the page says dark */\n' + ''.join(f'{scope(s, ".tw-dark " + SCOPE)}{{{d}}}\n' for s, d in dark))
    return ''.join(out)


def check() -> int:
    if not SERVED.is_file() or SERVED.read_text(encoding='utf-8') != generate():
        print(f'B-PRIME: {rel(SERVED)} is not what `scripts/b_prime_css.py build` makes (it is generated; never edit it)')
        return 1
    return 0


def build() -> int:
    SERVED.write_text(generate(), encoding='utf-8')
    print(f'Built {rel(SERVED)}')
    return 0


if __name__ == '__main__':
    command = sys.argv[1] if len(sys.argv) > 1 else ''
    if command not in ('check', 'build'):
        raise SystemExit(__doc__)
    raise SystemExit(check() if command == 'check' else build())
