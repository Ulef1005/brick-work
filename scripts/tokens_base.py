"""Brick Work's design tokens: the base copy, the Brick Work layer and the served stylesheet made from them (#158).

    python3 scripts/tokens_base.py check    the drift check (scripts/check.sh); exit 1 on drift
    python3 scripts/tokens_base.py sync     write design/tokens/tokens.css from the pinned design builder base
    python3 scripts/tokens_base.py build    write the served stylesheet and the JSON from the copy and the layer

Three files, one direction:
- design/tokens/tokens.css: the design builder's neutral base (ai-wiki .claude/skills/design-builder/base/tokens.css), copied
  unchanged below a provenance header (source path, ai-wiki commit, SHA-256). Never edited. A newer base is only noted;
  Brick Work switches its base as its own step, with a frame comparison (App Design Standard), never by a silent sync.
- design/tokens/brickwork-tokens.css: Brick Work's layer, loaded after the base. It redefines every colour role, the type
  and the radii; its values are the stylesheet the app served before the roll-out (no visual change, ADR 0022).
- static/web/toni/tokens-v2.css (served, generated): the base's body followed by the layer. design/tokens/brickwork-tokens.json
  (generated): every custom property per theme block, for tools.

`check` works without an ai-wiki checkout (CI): the copy's body must hash to its pinned SHA-256, and the served file and the JSON
must equal what `build` makes. With a checkout it also confirms the pinned commit holds that source. Standard library only.
Modelled on engram's scripts/tokens_base.py."""
import hashlib
import json
import os
import re
import subprocess
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / 'design' / 'tokens'
COPY = TOKENS / 'tokens.css'
LAYER = TOKENS / 'brickwork-tokens.css'
JSON_OUT = TOKENS / 'brickwork-tokens.json'
SERVED = ROOT / 'static' / 'web' / 'toni' / 'tokens-v2.css'
BASE_PATH = '.claude/skills/design-builder/base/tokens.css'
AI_WIKI = Path(os.environ.get('AI_WIKI') or Path.home() / 'Workspace/ai-wiki')
SERVED_HEADER = ('/* Brick Work design tokens, served. GENERATED by scripts/tokens_base.py build: never edit this file.\n'
                 '   Sources: design/tokens/tokens.css (the design builder base, pinned) and design/tokens/brickwork-tokens.css\n'
                 '   (Brick Work layer, loaded after the base). The name tokens-v2.css is kept so every page links it as before. */\n\n')


def rel(path: Path) -> str:
    try:
        return str(path.relative_to(ROOT))
    except ValueError:
        return str(path)


def header(commit: str, sha: str, vendored: str) -> str:
    return (f'/* Vendored from ai-wiki {BASE_PATH}\n   ai-wiki commit {commit}\n   Date: {vendored}\n'
            f'   source SHA-256: {sha}\n   Never edit this copy: scripts/tokens_base.py sync writes it, check pins it.\n*/\n\n')


def split_copy(text: str) -> tuple[dict, str]:
    head, body = text.split('*/', 1)
    sha = re.search(r'source SHA-256: ([0-9a-f]{64})', head)
    commit = re.search(r'ai-wiki commit ([0-9a-f]{7,40})', head)
    return {'sha': sha[1] if sha else None, 'commit': commit[1] if commit else None}, body.removeprefix('\n\n')


def blocks(css: str) -> dict:
    """`{selector path: {property: value}}` of a stylesheet's declarations, comments dropped, nesting joined with ' >> '."""
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    out, stack, buf = {}, [], ''
    for ch in css:
        if ch == '{':
            stack.append(' '.join(buf.split()))
            buf = ''
        elif ch == '}':
            for decl in buf.split(';'):
                if ':' in decl:
                    name, value = decl.split(':', 1)
                    out.setdefault(' >> '.join(stack), {})[name.strip()] = ' '.join(value.split())
            if stack:
                stack.pop()
            buf = ''
        else:
            buf += ch
    return out


def served_text() -> str:
    _, body = split_copy(COPY.read_text(encoding='utf-8'))
    return SERVED_HEADER + '/* ---- base (design/tokens/tokens.css) ---- */\n' + body.rstrip('\n') + \
        '\n\n/* ---- Brick Work layer (design/tokens/brickwork-tokens.css) ---- */\n' + LAYER.read_text(encoding='utf-8')


def json_text() -> str:
    tree = {selector: decls for selector, decls in blocks(LAYER.read_text(encoding='utf-8')).items()}
    return json.dumps({'source': 'design/tokens/brickwork-tokens.css', 'generated_by': 'scripts/tokens_base.py build', 'blocks': tree},
                      indent=2, ensure_ascii=False) + '\n'


def build() -> int:
    SERVED.write_text(served_text(), encoding='utf-8')
    JSON_OUT.write_text(json_text(), encoding='utf-8')
    print(f'Built {rel(SERVED)} and {rel(JSON_OUT)}')
    return 0


def problems() -> list[str]:
    """Every drift, empty when the tokens are in order. Works without ai-wiki."""
    found = []
    pin, body = split_copy(COPY.read_text(encoding='utf-8'))
    if not pin['sha'] or not pin['commit']:
        return ['design/tokens/tokens.css has no pinned ai-wiki commit and SHA-256 in its header']
    if hashlib.sha256(body.encode('utf-8')).hexdigest() != pin['sha']:
        found.append('design/tokens/tokens.css was edited: its body no longer hashes to the pinned source SHA-256 (never edit the copy)')
    base, layer = blocks(body), blocks(LAYER.read_text(encoding='utf-8'))
    for selector, decls in base.items():                       # the layer redefines all of it, so the base never shows through
        for name in decls:
            if name not in layer.get(selector, {}):
                found.append(f'the base sets {name} in {selector} and the Brick Work layer does not redefine it there')
    if SERVED.read_text(encoding='utf-8') != served_text():
        found.append(f'{rel(SERVED)} is not what `scripts/tokens_base.py build` makes (it is generated; never edit it)')
    if not JSON_OUT.is_file() or JSON_OUT.read_text(encoding='utf-8') != json_text():
        found.append(f'{rel(JSON_OUT)} is not what `scripts/tokens_base.py build` makes')
    return found


def check() -> int:
    found = problems()
    for line in found:
        print('TOKENS: ' + line)
    if found:
        return 1
    pin, _ = split_copy(COPY.read_text(encoding='utf-8'))
    note = ''
    if (AI_WIKI / '.git').exists():
        shown = subprocess.run(['git', '-C', str(AI_WIKI), 'show', f"{pin['commit']}:{BASE_PATH}"], capture_output=True)
        if shown.returncode != 0 or hashlib.sha256(shown.stdout).hexdigest() != pin['sha']:
            print(f"TOKENS: ai-wiki {pin['commit']} does not hold the pinned base source")
            return 1
        current = AI_WIKI / BASE_PATH
        if current.is_file() and hashlib.sha256(current.read_bytes()).hexdigest() != pin['sha']:
            note = ' NOTE: the design builder base has moved on; switching is its own step with a frame comparison.'
    else:
        note = ' (no ai-wiki checkout: the pinned commit itself not re-read)'
    print(f"Design tokens OK: base pinned to ai-wiki {pin['commit'][:8]} (SHA-256 {pin['sha'][:12]}), served file and JSON generated.{note}")
    return 0


def sync() -> int:
    """Write the copy from the base as committed in ai-wiki (bytes from `git show`, so the recorded commit and SHA-256 describe
    them). Nothing is written when git fails or the working tree differs from the committed base."""
    git = lambda *args: subprocess.run(['git', '-C', str(AI_WIKI), *args], capture_output=True)  # noqa: E731
    found = git('log', '-1', '--format=%h', '--', BASE_PATH)
    commit = found.stdout.decode().strip() if found.returncode == 0 else ''
    if not commit:
        sys.exit(f'sync refused: no commit of {BASE_PATH} in {AI_WIKI}; nothing written')
    shown = git('show', f'{commit}:{BASE_PATH}')
    if shown.returncode != 0:
        sys.exit(f'sync refused: git show {commit}:{BASE_PATH} failed; nothing written')
    raw = shown.stdout
    working = AI_WIKI / BASE_PATH
    if not working.is_file() or working.read_bytes() != raw:
        sys.exit(f'sync refused: {BASE_PATH} in the ai-wiki working tree differs from commit {commit}; nothing written')
    sha = hashlib.sha256(raw).hexdigest()
    TOKENS.mkdir(parents=True, exist_ok=True)
    COPY.write_text(header(commit, sha, date.today().isoformat()) + raw.decode('utf-8'), encoding='utf-8')
    print(f'Synced design/tokens/tokens.css from ai-wiki {commit} (source SHA-256: {sha})')
    return 0


if __name__ == '__main__':
    sys.exit({'check': check, 'sync': sync, 'build': build}[sys.argv[1]]())
